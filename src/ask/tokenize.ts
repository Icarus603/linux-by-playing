const S2T = new Map([...S].map((c, i) => [c, [...T][i]!]))

export function normalize(text: string): string {
  let t = [...text].map((c) => S2T.get(c) ?? c).join('')
  for (const [re, to] of NORMALIZE) t = t.replace(re, to)
  return t
}

export function tokenize(text: string): string[] {
  const out: string[] = []
  const t = normalize(text).toLowerCase()
  for (const m of t.matchAll(/[a-z0-9][a-z0-9_.+\-/]*|[㐀-鿿豈-﫿]+/g)) {
    const w = m[0]
    if (CJK.test(w)) {
      const cs = [...w]
      // 去掉停用字後相鄰的字也組成二元詞（「變很慢」→「變慢」），補足中間夾了雜字的情形
      const kept = cs.filter((c) => !STOP_UNI.has(c))
      for (let i = 0; i + 1 < kept.length; i++) {
        const bi = kept[i]! + kept[i + 1]!
        if (!STOP_BI.has(bi)) out.push(bi)
      }
      for (let i = 0; i < cs.length; i++) {
        if (!STOP_UNI.has(cs[i]!)) out.push(cs[i]!)
        if (i + 1 < cs.length) {
          const bi = cs[i]! + cs[i + 1]!
          if (!STOP_BI.has(bi) && !(STOP_UNI.has(cs[i]!) && STOP_UNI.has(cs[i + 1]!))) out.push(bi)
        }
      }
    } else {
      if (STOP_EN.has(w)) continue
      out.push(w)
      // 同時加入去掉路徑與副檔名的片段，提高命中率（例如 /etc/hosts → hosts）
      const parts = w.split(/[/.\-_]/).filter((p) => p.length > 1 && !STOP_EN.has(p))
      if (parts.length > 1) out.push(...parts)
    }
  }
  return out
}
